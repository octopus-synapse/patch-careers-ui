import { readdir, readFile, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const client = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = path.join(client, "src/app");
const output = path.join(app, "en");
const marker = "// @generated by scripts/sync-english-routes.mjs — do not edit.\n";

async function routes(dir, relative = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const found = [];
  for (const entry of entries) {
    if (entry.name === "en" && !relative) continue;
    const name = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await routes(path.join(dir, entry.name), name)));
    } else if (/\.tsx$/.test(name) && !/\.(native|ios|android)\.tsx$/.test(name)) {
      if (name.startsWith("+") || name === "_layout.tsx") continue;
      found.push(name);
    }
  }
  return found;
}

function webRouteName(source) {
  return source.replace(/(?:\.web)?\.tsx$/, ".web.tsx");
}

async function sync() {
  const check = process.argv.includes("--check");
  const sourceFiles = await routes(app);
  const chosen = new Map();
  for (const source of sourceFiles) {
    const target = webRouteName(source);
    if (!chosen.has(target) || source.endsWith(".web.tsx")) chosen.set(target, source);
  }
  const expected = new Map([
    ["_layout.web.tsx", `${marker}export { default } from "@/navigation/english-layout";\n`],
    ["_layout.tsx", `${marker}import { Stack } from "expo-router";\nexport default function NativeEnglishLayout() { return <Stack />; }\n`],
  ]);
  for (const [target, source] of chosen) {
    const from = path.posix.dirname(path.posix.join("en", target));
    let importPath = path.posix.relative(from, source).replace(/\.tsx$/, "");
    if (!importPath.startsWith(".")) importPath = `./${importPath}`;
    expected.set(target, `${marker}export { default } from "${importPath}";\nexport * from "${importPath}";\n`);
    const nativeTarget = target.replace(/\.web\.tsx$/, ".tsx");
    expected.set(nativeTarget, `${marker}import { Redirect } from "expo-router";\nexport default function NativeEnglishRedirect() { return <Redirect href="/" />; }\n`);
  }

  async function clean(dir, relative = "") {
    for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
      const name = path.posix.join(relative, entry.name);
      const absolute = path.join(dir, entry.name);
      if (entry.isDirectory()) await clean(absolute, name);
      else if (!expected.has(name)) {
        const text = await readFile(absolute, "utf8");
        if (!text.startsWith(marker)) throw new Error(`Unmanaged file in generated route tree: ${absolute}`);
        if (check) throw new Error(`Stale generated route: ${absolute}`);
        await rm(absolute);
      }
    }
  }
  if (!check) await mkdir(output, { recursive: true });
  await clean(output);
  for (const [name, content] of expected) {
    const absolute = path.join(output, name);
    if ((await readFile(absolute, "utf8").catch(() => "")) !== content) {
      if (check) throw new Error(`Missing or outdated generated route: ${absolute}`);
      await mkdir(path.dirname(absolute), { recursive: true });
      await writeFile(absolute, content);
    }
  }
  if (check) {
    console.log(`English aliases: ${expected.size} routes`);
  }
}

await sync();
